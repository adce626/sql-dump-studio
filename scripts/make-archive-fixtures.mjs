/**
 * Creates the archive fixtures used to test the different input formats:
 *   mysql-shop.sql.gz     gzip compressed SQL dump
 *   mysql-shop.tar        tar archive with a SQL dump inside
 *   mysql-shop.tar.gz     gzip compressed tar archive
 *   shop-database.tar     tar archive with a native SQLite database inside
 *   sqlserver-backup.bak  binary blob that cannot be opened (conversion needed)
 *   plain-dump.dump       plain SQL text with a .dump extension
 *
 * Run: node scripts/make-archive-fixtures.mjs
 */
import { gzipSync } from 'node:zlib';
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const fixtures = join(root, 'test', 'fixtures');

/* ------------------------------------------------------------------ *
 * Minimal tar writer
 * ------------------------------------------------------------------ */

function octal(value, length) {
  return value.toString(8).padStart(length - 1, '0') + '\0';
}

function tarHeader(name, size, mtime = 0) {
  const header = Buffer.alloc(512);
  header.write(name.slice(0, 100), 0, 'utf8');
  header.write(octal(0o644, 8), 100, 'ascii');
  header.write(octal(0, 8), 108, 'ascii');
  header.write(octal(0, 8), 116, 'ascii');
  header.write(octal(size, 12), 124, 'ascii');
  header.write(octal(mtime, 12), 136, 'ascii');
  header.write('        ', 148, 'ascii'); // checksum placeholder
  header.write('0', 156, 'ascii');
  header.write('ustar\0', 257, 'ascii');
  header.write('00', 263, 'ascii');
  header.write('root', 265, 'ascii');
  header.write('root', 297, 'ascii');

  let checksum = 0;
  for (const byte of header) checksum += byte;
  header.write(`${checksum.toString(8).padStart(6, '0')}\0 `, 148, 'ascii');
  return header;
}

function buildTar(members) {
  const blocks = [];
  for (const member of members) {
    const data = Buffer.isBuffer(member.data) ? member.data : Buffer.from(member.data, 'utf8');
    blocks.push(tarHeader(member.name, data.length));
    const padded = Buffer.alloc(Math.ceil(data.length / 512) * 512);
    data.copy(padded);
    blocks.push(padded);
  }
  blocks.push(Buffer.alloc(1024)); // end of archive
  return Buffer.concat(blocks);
}

/* ------------------------------------------------------------------ *
 * Fixtures
 * ------------------------------------------------------------------ */

const sql = readFileSync(join(fixtures, 'mysql-shop.sql'));
writeFileSync(join(fixtures, 'mysql-shop.sql.gz'), gzipSync(sql));
writeFileSync(join(fixtures, 'mysql-shop.tar'), buildTar([
  { name: 'mysql-shop.sql', data: sql },
  { name: 'readme.txt', data: 'Generated by scripts/make-archive-fixtures.mjs\n' },
]));
writeFileSync(join(fixtures, 'mysql-shop.tar.gz'), gzipSync(buildTar([
  { name: 'mysql-shop.sql', data: sql },
])));

const sqlitePath = join(fixtures, 'shop.sqlite');
if (existsSync(sqlitePath)) {
  writeFileSync(join(fixtures, 'shop-database.tar'), buildTar([
    { name: 'shop.sqlite', data: readFileSync(sqlitePath) },
  ]));
}

// A file that pretends to be a SQL Server backup: binary, not readable.
const fakeBackup = Buffer.alloc(4096);
fakeBackup.write('Microsoft SQL Server backup (fake fixture)\r\n', 0, 'ascii');
for (let i = 64; i < fakeBackup.length; i++) fakeBackup[i] = (i * 37) % 251;
writeFileSync(join(fixtures, 'sqlserver-backup.bak'), fakeBackup);

// A .dump file that really contains plain SQL text.
writeFileSync(join(fixtures, 'plain-dump.dump'), sql);

console.log('archive fixtures written to', fixtures);
